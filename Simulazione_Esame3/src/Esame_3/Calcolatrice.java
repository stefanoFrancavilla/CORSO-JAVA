package Esame_3;

public class Calcolatrice {

	//metodi
	
	public double somma(double x, double y)
	{
		return x + y;
	}
	public double sottrazione(double x , double y)
	{
		return x - y;
	}
	public int moltiplicazione (int x, int y)
	{
		return x * y;
	}
	public double divisione(double x, double y)
	{
		return x / y;
	}
}
