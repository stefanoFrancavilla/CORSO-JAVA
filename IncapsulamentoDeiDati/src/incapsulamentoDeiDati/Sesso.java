package incapsulamentoDeiDati;

public enum Sesso {
	MASCHIO,
	FEMMINA,
	SCONOSCIUTO
	
	/*
	 * con l'enum si possono definire dei tipi di dati personalizzati
	 * che possono assumere solo un insieme limitato di valori.
	 * In questo caso l'enum Sesso può assumere solo i valori MASCHIO o FEMMINA.
	 * 
	 * con final si indica che l'enum non può essere esteso da altre classi.
	 * con final non si possono aggiungere nuovi valori all'enum Sesso.
	 * 
	 * con static si indica che l'enum appartiene alla classe e non alle istanze della classe.
	 * 
	 * 
	 */
}
